/* Character names: read as whole words, never checked against the level
 * (shared with tools/check-content.js). */
const STORY_NAMES = new Set(["pip", "sam", "tom", "meg", "ben", "nell", "sid", "mum", "dad", "gran", "joe", "kate", "roy", "dan", "tim", "pam", "pat"]);

function bareWord(raw) {
  return String(raw).toLowerCase().replace(/[^a-z’'-]/g, "").replace(/[’']s$/, "").replace(/^[’']|[’']$/g, "");
}

/* What goes on a book's Get ready page, worked out from its own text so it
 * can't drift: the book's focus sounds, up to six words that use them (to
 * read with sound buttons first), and the tricky words in it. */
function storyPrep(st) {
  const focus = st.focus || [];
  const seen = new Set(), tricky = [], practise = [];
  const canon = (w) => trickyUpTo(MAX_LEVEL).find((t) => t.toLowerCase() === w) || w;
  for (const pg of st.pages) for (const raw of pg.text.split(/[\s.,!?“”"…]+/)) {
    const w = bareWord(raw);
    if (!w || seen.has(w)) continue;
    seen.add(w);
    if (isTrickyAt(w, st.level)) { tricky.push(canon(w)); continue; }
    if (STORY_NAMES.has(w) || practise.length >= 6) continue;
    const g = WORDS[w];
    // Phase 4 teaches no new sounds, only consonants side by side, so a
    // book with no focus sounds practises its adjacent-consonant words.
    if (g && (focus.length ? focus.some((f) => g.includes(f)) : minLevelFor(g) >= ADJACENT_SHORT_LEVEL)) practise.push(w);
  }
  return { focus, tricky, practise };
}

/* Books in a band, easiest first. */
function storiesForBand(band) {
  return STORIES.filter((s) => s.band === band).sort((a, b) => a.level - b.level);
}
function storyById(id) {
  return STORIES.find((s) => s.id === id);
}
function bandData(id) {
  return BANDS.find((b) => b.id === id) || BANDS[0];
}
